#!/usr/bin/env node
// Build the single-file OpenDN executables (no Node, git or npm needed on
// the user's computer). Uses Bun's compiler, which bundles the code and a
// JavaScript runtime into one file and can cross-compile, so one machine
// builds every target.
//
//   node scripts/build.js                 all targets → dist/
//   node scripts/build.js windows-x64     one target
//   node scripts/build.js native          the machine you are on
//
// Requires Bun ≥ 1.3 (https://bun.sh). Output: dist/opendn-<target>[.exe]
// plus dist/SHA256SUMS.txt.
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const BUILD = path.join(ROOT, 'build');
const DIST = path.join(ROOT, 'dist');

const TARGETS = {
  'windows-x64': { bun: 'bun-windows-x64', file: 'opendn-windows-x64.exe' },
  'linux-x64': { bun: 'bun-linux-x64', file: 'opendn-linux-x64' },
};

// shipped files the executable carries inside itself — read via src/assets.js
const EMBED_DIRS = ['templates', 'printer'];

function nativeTarget() {
  if (process.arch !== 'x64') throw new Error(`no build target for ${process.platform}-${process.arch}`);
  if (process.platform === 'win32') return 'windows-x64';
  if (process.platform === 'linux') return 'linux-x64';
  throw new Error(`no build target for ${process.platform} (build from source instead)`);
}

function writeEntry() {
  fs.rmSync(BUILD, { recursive: true, force: true });
  fs.mkdirSync(BUILD, { recursive: true });
  const embedded = {};
  for (const dir of EMBED_DIRS) {
    for (const name of fs.readdirSync(path.join(ROOT, dir)).sort()) {
      embedded[`${dir}/${name}`] = fs.readFileSync(path.join(ROOT, dir, name), 'utf8');
    }
  }
  fs.writeFileSync(path.join(BUILD, 'embedded.js'),
    `// generated by scripts/build.js — do not edit\nmodule.exports = ${JSON.stringify(embedded, null, 2)};\n`);
  fs.writeFileSync(path.join(BUILD, 'entry.js'),
    `// generated by scripts/build.js — do not edit\n` +
    `globalThis.__OPENDN_EMBEDDED__ = require('./embedded.js');\n` +
    `require('../bin/opendn.js');\n`);
  return Object.keys(embedded);
}

function sha256(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

function main() {
  let wanted = process.argv.slice(2);
  if (wanted.length === 0) wanted = Object.keys(TARGETS);
  wanted = wanted.map((t) => (t === 'native' ? nativeTarget() : t));
  for (const t of wanted) {
    if (!TARGETS[t]) throw new Error(`unknown target "${t}" (known: ${Object.keys(TARGETS).join(', ')}, native)`);
  }

  let bunVersion;
  try { bunVersion = execFileSync('bun', ['--version'], { encoding: 'utf8' }).trim(); }
  catch { throw new Error('Bun is required to build the executables — see https://bun.sh'); }
  const { version } = require('../package.json');
  console.log(`building opendn ${version} with Bun ${bunVersion}: ${wanted.join(', ')}`);

  const files = writeEntry();
  console.log(`embedded: ${files.join(', ')}`);

  fs.rmSync(DIST, { recursive: true, force: true });
  fs.mkdirSync(DIST, { recursive: true });
  for (const t of wanted) {
    const out = path.join(DIST, TARGETS[t].file);
    execFileSync('bun', [
      'build', '--compile', `--target=${TARGETS[t].bun}`,
      // optional pdf.js rendering modules — OpenDN only reads text
      '--external', 'canvas', '--external', 'path2d-polyfill',
      path.join(BUILD, 'entry.js'), '--outfile', out,
    ], { cwd: ROOT, stdio: 'inherit' });
  }

  const sums = wanted.map((t) => `${sha256(path.join(DIST, TARGETS[t].file))}  ${TARGETS[t].file}`);
  fs.writeFileSync(path.join(DIST, 'SHA256SUMS.txt'), `${sums.join('\n')}\n`);
  for (const t of wanted) {
    const mb = (fs.statSync(path.join(DIST, TARGETS[t].file)).size / 1048576).toFixed(0);
    console.log(`dist/${TARGETS[t].file}  ${mb} MB`);
  }
  console.log('dist/SHA256SUMS.txt');
}

try { main(); } catch (e) { console.error(`build failed: ${e.message}`); process.exit(1); }
